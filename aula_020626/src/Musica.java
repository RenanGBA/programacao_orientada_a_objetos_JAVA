public class Musica {

    private String titulo, artista;

    public Musica(String mTitulo, String mArtista) {
        this.titulo = mTitulo;
        this.artista = mArtista;
    }

    public String getTitulo() {
        return this.titulo;
    }

    public String getArtista() {
        return this.artista;
    }
}
